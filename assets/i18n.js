function detect_lang() {
	for (const raw of navigator.languages || [navigator.language || 'en']) {
		const code = raw.toLowerCase()
		if (I18N_LANGS[code]) return code
		if (/^zh-(tw|hk|mo)/.test(code) || code.includes('hant')) return 'zh-tw'
		const base = code.split('-')[0]
		if (I18N_LANGS[base]) return base
	}
	return 'en'
}

const I18N_LANG = detect_lang()

function t(key) {
	return I18N_LANGS[I18N_LANG][key] ?? I18N_LANGS.en[key] ?? key
}

document.documentElement.lang = I18N_LANG
for (const el of document.querySelectorAll('[data-i18n]')) {
	el.textContent = t(el.dataset.i18n) + (el.dataset.i18nSuffix ? ' ' + el.dataset.i18nSuffix : '')
}
for (const el of document.querySelectorAll('[data-i18n-placeholder]')) {
	el.placeholder = t(el.dataset.i18nPlaceholder)
}
